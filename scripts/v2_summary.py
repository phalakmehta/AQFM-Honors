"""AQFM v2 on Delhi, 2025 test: tables generated from the results files only (step 9).

    python scripts/v2_summary.py v2 > results/v2_delhi_summary.md      # written by scripts/pipeline_v2_delhi.sh

Compares the v2 city preset with v1 (results/aqfm_do3_*) and the baselines, from the same
files results/TABLES.md is generated from.
"""
import glob
import json
import os
import re
import sys

import torch

TAG = sys.argv[1] if len(sys.argv) > 1 else "v2"
H = ("1h", "6h", "24h", "72h")


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def mae(src, c, h, section="AQFM"):
    """MAE from a results file (section = model key) or a seed-stats file (mean ± std)."""
    if src is None:
        return "–"
    if "metrics" in src:
        s = src["metrics"].get(f"{section}/{c}/{h}/MAE")
        return "–" if s is None else f"{s['mean']:.2f} ± {s['std']:.2f}"
    d = src[section][c]
    v = d["24h_aqi"]["Severe"]["MAE"] if h == "severe" else d[h]["MAE"]
    return f"{v:.1f}" if h == "severe" else f"{v:.2f}"


def severe_stats(src, section="AQFM"):
    if src is None:
        return "–"
    if "metrics" in src:
        s = src["metrics"].get(f"{section}/PM2.5/24h_aqi/Severe/MAE")
        return "–" if s is None else f"{s['mean']:.1f} ± {s['std']:.1f}"
    return mae(src, "PM2.5", "severe", section)


R = lambda p: load(p)
rows = [
    (f"**AQFM v2 ensemble (3 seeds)**", R(f"results/{TAG}_ens3_results.json"), "AQFM"),
    ("AQFM v2 single model, mean ± std (3 seeds)", R(f"results/{TAG}_seeds_stats.json"), "AQFM"),
    ("AQFM v1 ensemble (3 seeds)", R("results/aqfm_do3_ens3_results.json"), "AQFM"),
    ("AQFM v1 single model, mean ± std (3 seeds)", R("results/aqfm_do3_seeds_stats.json"), "AQFM"),
    ("AQFM v2 no future weather, ensemble (3 seeds)", R(f"results/{TAG}_nofm_ens3_results.json"), "AQFM"),
    ("AQFM v2 no future weather, mean ± std (3 seeds)", R(f"results/{TAG}_nofm_seeds_stats.json"), "AQFM"),
    ("AQFM v1 no future weather, ensemble (3 seeds)", R("results/aqfm_do3_nofm_ens3_results.json"), "AQFM"),
    ("AQFM v1 no future weather, mean ± std (3 seeds)", R("results/aqfm_do3_nofm_seeds_stats.json"), "AQFM"),
    ("XGBoost + future ERA5", R("baselines/results/xgboost_future_met_results.json"), "XGBoost + future ERA5"),
    ("XGBoost (no future met)", R("baselines/results/xgboost_results.json"), "XGBoost"),
    ("PatchTST ensemble (3 seeds)", R("baselines/results/patchtst_ens3_results.json"), "PatchTST"),
    ("E-STGCN ensemble (3 seeds)", R("baselines/results/estgcn_ens3_results.json"), "E-STGCN"),
    ("Persistence", R("baselines/results/classical_results.json"), "Persistence"),
]

out = [f"# AQFM v2 (city preset) on Delhi: 2025 test", "",
       f"Generated by `scripts/v2_summary.py {TAG}` from the results files. Same test points and scoring code as",
       "`results/TABLES.md` (daily 00:00 origins in 2025, 15-min points, µg/m³). v2 = `AQFMConfig.city()` trained on",
       "`data/delhi/` (CPCB coordinates, location facts); v1 = the 23.8M model on `data/preprocessed/`.",
       "AQFM rows are given the ERA5 weather for the forecast hours (as is XGBoost + future ERA5), except the rows",
       "marked \"no future weather\" (`--no-future-met`).", ""]

# selection
cands = sorted(glob.glob(f"runs/{TAG}_s0_do*/best.pt"))
if cands:
    out += ["## Dropout, chosen on the 2024 validation score (seed 0)", "", "| run | dropout | best step | validation score |",
            "|---|---|---|---|"]
    for p in cands:
        ck = torch.load(p, map_location="cpu", weights_only=False)
        v, c = ck["val"], ck["cfg"]
        out.append(f"| `{os.path.dirname(p)}` | {c['dropout']} | {ck['step']} | "
                   f"{c['w_nll'] * v['nll_forecast'] + c['w_crps'] * v['crps_forecast']:.4f} |")
    out.append("")

for c in ("PM2.5", "PM10"):
    sev = c == "PM2.5"
    out += [f"## {c} MAE (µg/m³)", "", "| Model | " + " | ".join(H) + (" | Severe, 24 h |" if sev else " |"),
            "|---|" + "---|" * (len(H) + sev)]
    for name, src, sec in rows:
        cells = [mae(src, c, h, sec) for h in H] + ([severe_stats(src, sec)] if sev else [])
        out.append(f"| {name} | " + " | ".join(cells) + " |")
    out.append("")

# probabilistic (AQFM only)
out += ["## PM2.5 at 24 h: CRPS and interval coverage (AQFM ensembles)", "", "| Model | CRPS | 90% coverage | 95% coverage |",
        "|---|---|---|---|"]
for name, p in ((f"AQFM v2 ensemble", f"results/{TAG}_ens3_results.json"), ("AQFM v1 ensemble", "results/aqfm_do3_ens3_results.json"),
                ("AQFM v2 ensemble, no future weather", f"results/{TAG}_nofm_ens3_results.json"),
                ("AQFM v1 ensemble, no future weather", "results/aqfm_do3_nofm_ens3_results.json")):
    s = load(p)
    if s:
        e = s["AQFM_extras"]["PM2.5"]["24h"]
        out.append(f"| {name} | {e['crps']:.2f} | {e['coverage90']:.3f} | {e['coverage95']:.3f} |")
out.append("")

# unseen stations
ho = [("new station that has its own history (hold-out run)", f"results/{TAG}_holdout4_newstation_results.json"),
      ("virtual sensing (no readings at the station; hold-out run)", f"results/{TAG}_holdout4_virtual_results.json"),
      ("same 4 stations, seen in training (all-station model, seed 0)", f"results/{TAG}_s0_on_holdout4_results.json")]
if any(load(p) for _, p in ho):
    st = (load(ho[0][1]) or {}).get("stations")
    out += ["## Unseen stations (4 hidden in training, seed 0), PM2.5 MAE (µg/m³)", "",
            f"Hidden stations (indices): {st}. Other hidden stations are not used as neighbours.", "",
            "| Test | " + " | ".join(H) + " |", "|---|" + "---|" * len(H)]
    for name, p in ho:
        s = load(p)
        out.append(f"| {name} | " + " | ".join(mae(s, "PM2.5", h) for h in H) + " |")
    out.append("")

# nearest-neighbour bands
bands = sorted(glob.glob(f"results/{TAG}_ens3_nnband_*_results.json"))
if bands:
    out += ["## By distance from each station to its nearest neighbour (ensembles), PM2.5 MAE (µg/m³)", "",
            "| Band | stations | model | " + " | ".join(H) + " |", "|---|---|---|" + "---|" * len(H)]
    for p in bands:
        b = re.search(r"nnband_(.+)_results", p).group(1)
        label = {"0_5": "0–5 km", "5_15": "5–15 km", "15p": "> 15 km"}.get(b, b)
        for model, q in (("v2", p), ("v1", p.replace(f"{TAG}_ens3_", f"{TAG}_v1ens3_"))):
            s = load(q)
            n = len(s["stations"]) if s else "–"
            out.append(f"| {label} | {n} | {model} | " + " | ".join(mae(s, "PM2.5", h) for h in H) + " |")
    out.append("")

print("\n".join(out))
